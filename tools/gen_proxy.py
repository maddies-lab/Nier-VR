#!/usr/bin/env python3
"""Generate a forwarding proxy for a system DLL.

Reads the export table of a reference DLL (via llvm-readobj) and writes:
  <out>/<name>.def        module-definition file mapping each export to a stub
  <out>/<name>_stubs.S    one `jmp *slot(%rip)` stub per export
  <out>/<name>_table.cpp  export names/ordinals + the slot table filled at load

Usage: gen_proxy.py <reference.dll> <proxy-name> <out-dir>
"""
import os
import re
import subprocess
import sys


def read_exports(dll):
    text = subprocess.run(["llvm-readobj", "--coff-exports", dll],
                          check=True, capture_output=True, text=True).stdout
    exports = []
    for block in re.findall(r"Export \{(.*?)\}", text, re.S):
        ordinal = int(re.search(r"Ordinal: (\d+)", block).group(1))
        name = re.search(r"Name: ?(.*)", block).group(1).strip()
        exports.append((ordinal, name))
    return exports


def main():
    dll, proxy, out = sys.argv[1], sys.argv[2], sys.argv[3]
    exports = read_exports(dll)
    os.makedirs(out, exist_ok=True)

    with open(os.path.join(out, f"{proxy}.def"), "w") as f:
        f.write(f"LIBRARY {proxy}.dll\nEXPORTS\n")
        for i, (ordinal, name) in enumerate(exports):
            if name:
                f.write(f"    {name}=proxy_stub_{i} @{ordinal}\n")
            else:
                f.write(f"    ord_{ordinal}=proxy_stub_{i} @{ordinal} NONAME\n")

    with open(os.path.join(out, f"{proxy}_stubs.S"), "w") as f:
        f.write("# Generated by tools/gen_proxy.py - do not edit.\n.text\n")
        for i in range(len(exports)):
            f.write(f".globl proxy_stub_{i}\nproxy_stub_{i}:\n"
                    f"    jmp *g_proxy_slots+{8 * i}(%rip)\n")

    with open(os.path.join(out, f"{proxy}_table.cpp"), "w") as f:
        f.write("// Generated by tools/gen_proxy.py - do not edit.\n"
                '#include "proxy/proxy.hpp"\n\n'
                f'extern "C" {{\nvoid* g_proxy_slots[{len(exports)}]{{}};\n}}\n\n'
                "namespace proxy {\n"
                f'const wchar_t* const k_system_dll = L"{proxy}.dll";\n'
                f"const Export k_exports[{len(exports)}] = {{\n")
        for ordinal, name in exports:
            f.write(f'    {{"{name}", {ordinal}}},\n' if name else f"    {{nullptr, {ordinal}}},\n")
        f.write(f"}};\nconst size_t k_export_count = {len(exports)};\n"
                "void** const k_slots = g_proxy_slots;\n}\n")

    print(f"{len(exports)} exports written for {proxy}.dll")


if __name__ == "__main__":
    main()
